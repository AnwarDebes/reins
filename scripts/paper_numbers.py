"""Regenerate paper/_numbers.tex from results/*.json.

Single source of truth: every headline number in the paper is a LaTeX macro whose
default (in reins.tex) equals the committed result and whose override here is
identical.  Run after experiments/run_all.py.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(__file__)
RESULTS = os.path.join(HERE, "..", "results")
OUT = os.path.join(HERE, "..", "paper", "_numbers.tex")


def load(name):
    with open(os.path.join(RESULTS, name)) as f:
        return json.load(f)


def f3(x): return f"{x:.3f}"
def f2(x): return f"{x:.2f}"
def i(x): return f"{int(round(x))}"


def cmd(name, val):
    return f"\\renewcommand{{\\{name}}}{{{val}}}"


def main():
    lines = ["% Auto-generated by scripts/paper_numbers.py; do not edit by hand."]

    e1 = load("safety_utility.json"); s = e1["summary"]
    lines += [
        cmd("cupReins", f3(s["reins"]["cup_mean"])),
        cmd("cupReinsSd", f3(s["reins"]["cup_std"])),
        cmd("cupBlock", f3(s["block"]["cup_mean"])),
        cmd("cupBlockSd", f3(s["block"]["cup_std"])),
        cmd("cupNoshield", f3(s["noshield"]["cup_mean"])),
        cmd("asrReins", f3(s["reins"]["asr_mean"])),
        cmd("asrBlock", f3(s["block"]["asr_mean"])),
        cmd("asrNoshield", f3(s["noshield"]["asr_mean"])),
    ]
    fr = {p["label"]: p for p in e1["frontier"]}
    lines += [
        cmd("frontierBlock", f3(fr["block (suppress only)"]["cup_mean"])),
        cmd("frontierSub", f3(fr["+substitute"]["cup_mean"])),
        cmd("frontierAuthz", f3(fr["+insert-authorize"]["cup_mean"])),
        cmd("frontierFull", f3(fr["+insert-audit (full)"]["cup_mean"])),
    ]

    e2 = load("soundness.json")
    lines += [
        cmd("soundFull", f3(e2["shieldable_full"]["soundness_rate_mean"])),
        cmd("failFull", i(e2["shieldable_full"]["enforcement_failures_total"])),
        cmd("soundBadNoEsc", f3(e2["nonshieldable_no_escalation"]["soundness_rate_mean"])),
        cmd("failBadNoEsc", i(e2["nonshieldable_no_escalation"]["enforcement_failures_total"])),
        cmd("soundBadEsc", f3(e2["gaps_with_escalation"]["soundness_rate_mean"])),
    ]

    e3 = load("transparency.json")
    lines += [
        cmd("certMinRate", f3(e3["certified_minimal_rate"])),
        cmd("stepsChecked", i(e3["n_steps_checked"])),
        cmd("globalAgree", f3(e3["per_step_vs_global_agreement"])),
        cmd("globalTraj", i(e3["n_trajectories_global"])),
        cmd("globalGap", f"{e3['max_total_cost_gap']:.1f}"),
        cmd("interventCompliant", f3(e3["transparency_intervention_rate_compliant_mean"])),
    ]

    e4 = load("certificate.json")
    lines += [
        cmd("tamperRate", f2(e4["tamper_overall_rate"])),
        cmd("overCaught", f2(e4["minimality_over_restriction_caught_rate"])),
        cmd("underCaught", i(e4["minimality_under_restriction_caught"])),
        cmd("underTrials", i(e4["minimality_trials"])),
        cmd("verifyUs", i(e4["verify_us_per_session"])),
        cmd("verifyEntries", i(e4["verify_session_entries"])),
    ]

    e5 = load("systems.json"); lat = e5["latency"]
    lines += [
        cmd("shieldMed", f2(lat["median_us"])),
        cmd("shieldPnn", f2(lat["p99_us"])),
        cmd("candMean", f2(lat["candidate_set_mean"])),
        cmd("monMem", i(e5["monitor_memory_bytes"])),
        cmd("ledgerBytes", i(e5["ledger_bytes_per_entry"])),
    ]

    e6 = load("robustness.json"); abl = e6["capability_ablation"]
    lines += [
        cmd("exportBudget", i(e6["export_budget"])),
        cmd("ablFull", f3(abl["full"]["cup_mean"])),
        cmd("ablNoIns", f3(abl["no_insert"]["cup_mean"])),
        cmd("ablNoEsc", f3(abl["no_insert_no_escalation"]["cup_mean"])),
        cmd("ablNoEscSound", f3(abl["no_insert_no_escalation"]["soundness_mean"])),
        cmd("ablBlock", f3(abl["block"]["cup_mean"])),
    ]

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(OUT), f"({len(lines)-1} macros)")


if __name__ == "__main__":
    main()
